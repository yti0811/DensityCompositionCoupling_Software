#!/usr/bin/env python3
"""
07_KKT_boundary_validation.py

Numerical certification of the nine BG-KKT states generated by
01_equilibrium_regime_map.py.

This script deliberately reuses the production equilibrium model/solver instead of
reimplementing the thermodynamics.  It:
  1. identifies the nine BG-K* states from the manuscript master table (or from a
     built-in expected list if --master is omitted),
  2. reruns the production Case-II profile,
  3. extracts every spatial point for which the selected equilibrium is on
     the active eta=1 boundary,
  4. recomputes Rx, Reta and the full local Hessian at those points,
  5. classifies each selected boundary point as strict / marginal / violated,
  6. applies Hxx>0 for strict points and the Schur-complement projected
     curvature for marginal points,
  7. verifies that the selected boundary candidate is the lowest-g candidate
     found by the same production candidate search,
  8. performs a direct feasible inward perturbation check by minimizing g(x,eta)
     at eta=1-delta for several small positive delta values,
  9. writes pointwise and statewise audit tables plus a text summary.

Expected companion files in the same directory (or provide command-line paths):
  01_equilibrium_regime_map.py
  05_manuscript_results_output/manuscript_state_table.csv

Example:
  python 07_KKT_boundary_validation.py

Outputs are written to 07_KKT_boundary_validation_output/.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar

# Numerical classification tolerance requested in the revised SI.
KKT_EPS = 1.0e-9
# Small inward perturbations used only as an independent local check.
INWARD_DELTAS = (1.0e-6, 1.0e-5, 1.0e-4)

SCRIPT_DIR = Path(__file__).resolve().parent


# Expected KKT states from the audited Step18 production table.
EXPECTED_KKT = [
    (0.5, -1.0),
    (0.5, -0.8),
    (0.2, -0.8),
    (0.2, -0.6),
    (0.1, -0.6),
    (0.2, -0.4),
    (0.1, -0.4),
    (0.2, -0.2),
    (0.1, -0.2),
]


def load_module(path: Path):
    spec = importlib.util.spec_from_file_location("step14_prod", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import production solver: {path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def find_kkt_states(master_path: Path | None) -> list[tuple[float, float]]:
    if master_path is None or not master_path.exists():
        return EXPECTED_KKT.copy()
    d = pd.read_csv(master_path)
    if "production_class" in d.columns:
        q = d[d["production_class"].astype(str).eq("BG_KKT")]
    elif "final_class" in d.columns:
        q = d[d["final_class"].astype(str).str.startswith("BG-K")]
    else:
        raise ValueError("Master table lacks production_class/final_class.")
    states = sorted({(float(r.kappa), float(r.chi_ps)) for _, r in q.iterrows()})
    if len(states) != 9:
        raise RuntimeError(f"Expected 9 KKT states, found {len(states)}: {states}")
    return states


def hessian_components(x: float, eta: float, par):
    s = eta - x
    r = par.r_p
    hxx = 1.0/(r*x) + 1.0/s + par.chi_pp - 2.0*par.chi_ps + par.chi_ss
    hxe = (1.0 - 1.0/r)/eta - 1.0/s + par.chi_ps - par.chi_ss
    hee = 1.0/s - 1.0/eta - (1.0 - 1.0/r)*x/eta**2 + par.kappa + par.chi_ss
    schur = hee - hxe*hxe/hxx if np.isfinite(hxx) and hxx != 0.0 else np.nan
    return hxx, hxe, hee, schur


def classify_point(rx, reta, hxx, schur):
    if abs(rx) > KKT_EPS or reta > KKT_EPS:
        typ = "violated"
        passed = False
    elif reta < -KKT_EPS:
        typ = "strict"
        passed = bool(hxx > KKT_EPS)
    else:
        typ = "marginal"
        passed = bool((hxx > KKT_EPS) and (schur > KKT_EPS))
    return typ, passed


def minimize_x_at_eta(step14, eta, log_q, par, x_hint):
    # Direct 1-D constrained minimization along a fixed eta slice.
    lo = max(1.0e-12, min(x_hint * 0.25, eta * 1.0e-4))
    hi = eta - 1.0e-12
    if not (lo < hi):
        lo = 1.0e-12
    res = minimize_scalar(
        lambda x: step14.local_grand_density(float(x), float(eta), float(log_q), par),
        bounds=(lo, hi), method="bounded",
        options={"xatol": 1.0e-13, "maxiter": 1000},
    )
    return res


def candidate_gap_at_point(step14, log_q, par, selected_g):
    interior = step14.find_interior_minima(float(log_q), par, continuation=None)
    boundary = step14.find_boundary_minima(float(log_q), par, nscan=6000)
    cand = sorted(interior + boundary, key=lambda q: q["g"])
    if not cand:
        return np.nan, np.nan, 0, 0, 0
    best_delta = float(cand[0]["g"] - selected_g)
    gap = float(cand[1]["g"] - cand[0]["g"]) if len(cand) >= 2 else np.inf
    return best_delta, gap, len(cand), len(interior), len(boundary)


def audit_state(step14, kappa, chi, L, dz):
    par = step14.ModelParams(kappa=float(kappa), chi_ps=float(chi))
    wall = step14.WallParams()
    z = step14.make_grid(L=L, dz=dz)
    loc = step14.local_state_quantities(z, par, wall)
    log_q = loc["log_q"]

    bulk = step14.audit_bulk_global(par)
    if bulk.get("bulk_class") != "BG":
        raise RuntimeError(f"({kappa},{chi}) is not BG on rerun: {bulk}")

    II = step14.solve_caseII_profile(z, log_q, par)
    if not II.get("success", False):
        raise RuntimeError(f"Case-II solver failed for ({kappa},{chi}) at z={II.get('failed_z')}")

    bidx = np.flatnonzero(np.asarray(II["state_type"], object) == "BOUNDARY")
    if len(bidx) == 0:
        raise RuntimeError(f"No selected boundary points for expected KKT state ({kappa},{chi}).")

    rows = []
    for i in bidx:
        x = float(II["phi_p"][i])
        eta = float(II["eta"][i])
        g0 = float(II["g"][i])
        lq = float(log_q[i])
        rx = float(step14.residual_x(x, eta, lq, par))
        reta = float(step14.residual_eta(x, eta, par))
        hxx, hxe, hee, schur = hessian_components(x, eta, par)
        typ, second_pass = classify_point(rx, reta, hxx, schur)

        best_dg, competitor_gap, nc, ni, nb = candidate_gap_at_point(step14, lq, par, g0)

        inward = {}
        inward_all_nonnegative = True
        for delta in INWARD_DELTAS:
            eta_in = 1.0 - delta
            res = minimize_x_at_eta(step14, eta_in, lq, par, x)
            dg = float(res.fun - g0) if res.success and np.isfinite(res.fun) else np.nan
            inward[f"inward_dg_{delta:.0e}"] = dg
            inward[f"inward_success_{delta:.0e}"] = bool(res.success)
            if (not np.isfinite(dg)) or dg < -1.0e-10:
                inward_all_nonnegative = False

        rows.append({
            "kappa": kappa,
            "chi_ps": chi,
            "z_over_lambda": float(z[i]),
            "phi_p": x,
            "eta": eta,
            "phi_v": 1.0 - eta,
            "g_selected": g0,
            "Rx": rx,
            "Reta": reta,
            "Hxx": hxx,
            "Hxeta": hxe,
            "Hetaeta": hee,
            "Schur_density_curvature": schur,
            "KKT_type": typ,
            "second_order_pass": second_pass,
            "production_Rmax": float(II["Rmax"][i]),
            "production_candidate_count": int(II["n_total"][i]),
            "production_interior_count": int(II["n_interior"][i]),
            "production_boundary_count": int(II["n_boundary"][i]),
            "reaudit_candidate_count": nc,
            "reaudit_interior_count": ni,
            "reaudit_boundary_count": nb,
            "selected_minus_reaudit_best_g": best_dg,
            "next_candidate_gap": competitor_gap,
            "inward_all_nonnegative": inward_all_nonnegative,
            **inward,
        })

    return pd.DataFrame(rows), II, bulk


def summarize_state(df):
    strict_n = int((df.KKT_type == "strict").sum())
    marginal_n = int((df.KKT_type == "marginal").sum())
    violated_n = int((df.KKT_type == "violated").sum())
    finite_gap = df.loc[np.isfinite(df.next_candidate_gap), "next_candidate_gap"]
    return {
        "kappa": float(df.kappa.iloc[0]),
        "chi_ps": float(df.chi_ps.iloc[0]),
        "boundary_z_count": len(df),
        "z_min": float(df.z_over_lambda.min()),
        "z_max": float(df.z_over_lambda.max()),
        "max_abs_Rx": float(df.Rx.abs().max()),
        "max_Reta": float(df.Reta.max()),
        "min_Reta": float(df.Reta.min()),
        "min_Hxx": float(df.Hxx.min()),
        "min_Schur_density_curvature": float(df.Schur_density_curvature.min()),
        "strict_count": strict_n,
        "marginal_count": marginal_n,
        "violated_count": violated_n,
        "second_order_all_pass": bool(df.second_order_pass.all()),
        "inward_all_pass": bool(df.inward_all_nonnegative.all()),
        "max_abs_selected_minus_reaudit_best_g": float(df.selected_minus_reaudit_best_g.abs().max()),
        "min_next_candidate_gap": float(finite_gap.min()) if len(finite_gap) else np.inf,
        "certification": "PASS" if bool(df.second_order_pass.all() and df.inward_all_nonnegative.all() and (df.KKT_type != "violated").all()) else "FAIL",
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--step14", default=str(SCRIPT_DIR / "01_equilibrium_regime_map.py"))
    ap.add_argument("--master", default=str(SCRIPT_DIR / "05_manuscript_results_output" / "manuscript_state_table.csv"))
    ap.add_argument("--outdir", default=str(SCRIPT_DIR / "07_KKT_boundary_validation_output"))
    ap.add_argument("--L", type=float, default=20.0)
    ap.add_argument("--dz", type=float, default=0.05)
    args = ap.parse_args()

    step14_path = Path(args.step14).resolve()
    master_path = Path(args.master).resolve()
    outdir = Path(args.outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    if not step14_path.exists():
        raise FileNotFoundError(step14_path)
    step14 = load_module(step14_path)
    states = find_kkt_states(master_path if master_path.exists() else None)

    print("="*72)
    print("KKT BOUNDARY VALIDATION")
    print("="*72)
    print(f"Production solver : {step14_path}")
    print(f"Grid              : L={args.L:g}, dz={args.dz:g}")
    print(f"KKT states        : {len(states)}")

    all_points = []
    summaries = []
    for kappa, chi in states:
        print(f"Auditing kappa={kappa:g}, chi_ps={chi:g} ...", flush=True)
        pts, II, bulk = audit_state(step14, kappa, chi, args.L, args.dz)
        all_points.append(pts)
        s = summarize_state(pts)
        s["boundary_fraction_rerun"] = float(II["boundary_fraction"])
        s["profile_boundary_z_count_rerun"] = int(II["boundary_z_count"])
        s["bulk_class_rerun"] = bulk["bulk_class"]
        summaries.append(s)
        print(
            f"  boundary={len(pts):3d}, strict/marginal/violated="
            f"{s['strict_count']}/{s['marginal_count']}/{s['violated_count']}, "
            f"max Reta={s['max_Reta']:.3e}, min Hxx={s['min_Hxx']:.3e}, "
            f"min Schur={s['min_Schur_density_curvature']:.3e}, {s['certification']}"
        )

    pointwise = pd.concat(all_points, ignore_index=True)
    statewise = pd.DataFrame(summaries).sort_values(["kappa", "chi_ps"], ascending=[False, True])

    pointwise.to_csv(outdir / "KKT_boundary_pointwise.csv", index=False)
    statewise.to_csv(outdir / "KKT_state_summary.csv", index=False)

    total_strict = int((pointwise.KKT_type == "strict").sum())
    total_marginal = int((pointwise.KKT_type == "marginal").sum())
    total_violated = int((pointwise.KKT_type == "violated").sum())
    overall_pass = bool((statewise.certification == "PASS").all())

    lines = [
        "KKT BOUNDARY VALIDATION -- SUMMARY",
        "="*60,
        f"KKT parameter states: {len(statewise)}",
        f"Total selected boundary z-points: {len(pointwise)}",
        f"Point classification strict/marginal/violated: {total_strict}/{total_marginal}/{total_violated}",
        f"Global max |Rx|: {pointwise.Rx.abs().max():.12e}",
        f"Global max Reta (must be <= tolerance): {pointwise.Reta.max():.12e}",
        f"Global min Reta: {pointwise.Reta.min():.12e}",
        f"Global min Hxx: {pointwise.Hxx.min():.12e}",
        f"Global min Schur density curvature: {pointwise.Schur_density_curvature.min():.12e}",
        f"All second-order tests pass: {bool(pointwise.second_order_pass.all())}",
        f"All direct inward perturbation checks pass: {bool(pointwise.inward_all_nonnegative.all())}",
        f"All nine state certifications pass: {overall_pass}",
        "",
        "Interpretation:",
        "  strict   : Reta < -1e-9; Hxx>1e-9 is the relevant tangent-curvature test.",
        "  marginal : |Reta| <= 1e-9; Hxx>1e-9 and Schur curvature>1e-9 are required.",
        "  violated : Rx or Reta violates the first-order KKT tolerance.",
    ]
    (outdir / "KKT_validation_summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("-"*72)
    print(f"Total boundary points = {len(pointwise)}")
    print(f"strict/marginal/violated = {total_strict}/{total_marginal}/{total_violated}")
    print(f"All second-order tests pass = {bool(pointwise.second_order_pass.all())}")
    print(f"All inward checks pass = {bool(pointwise.inward_all_nonnegative.all())}")
    print(f"OVERALL = {'PASS' if overall_pass else 'FAIL'}")
    print(f"Outputs: {outdir}")


if __name__ == "__main__":
    main()
